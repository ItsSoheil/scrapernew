def clean_text(text):
    lines = [line.strip() for line in text.split('\n') if line.strip()]
    return lines

def parse_categories_structure(lines):
    parsed_data = []
    current_root = ""
    current_parent = ""
    
    for line in lines:
        if line == "همه کالاها":
            continue
            
        if line in root_categories:
            current_root = line
            current_parent = ""
            continue
            
        if current_root:
            if not current_parent:
                current_parent = line
            else:
                parsed_data.append({
                    "root": current_root,
                    "parent": current_parent,
                    "item": line
                })
                
    return parsed_data

