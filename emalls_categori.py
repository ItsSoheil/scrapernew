        if current_line in second_level_categories:
            if not path:
                i += 1
                continue
            if len(path) == 1:
                path.append(current_line)
            else:
                root = path[0]
                parent = path[1]
                parsed_data.append({"root": root, "parent": parent, "item": current_line})
                path = [root, current_line]
            i += 1
            continue
            
        if i + 1 < n and lines[i+1] == current_line:
            if not path:
                i += 1
                continue
            if len(path) == 1:
                root = path[0]
                parsed_data.append({"root": root, "parent": "", "item": current_line})
